"""
Alembic environment config.

The DB URL is pulled from app.database.config.settings (which reads
DATABASE_URL from .env), not hardcoded in alembic.ini - so migrations
always target whatever database the app itself is configured to use,
with a single source of truth for the connection string.
"""
import sys
from pathlib import Path
from logging.config import fileConfig

from sqlalchemy import engine_from_config, pool
from alembic import context

# Make the app package importable when alembic is run from backend/
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app.database.config import settings
from app.database.session import Base
# Import every model so they register on Base.metadata before autogenerate
# inspects it - forgetting one here means it silently gets left out of
# autogenerated migrations.
from app.models import job, resume, analysis  # noqa: F401

config = context.config
config.set_main_option("sqlalchemy.url", settings.DATABASE_URL)

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = Base.metadata


def run_migrations_offline() -> None:
    url = config.get_main_option("sqlalchemy.url")
    context.configure(
        url=url,
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(connection=connection, target_metadata=target_metadata)
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
